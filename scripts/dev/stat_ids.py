"""Writes src/GameServer.Gateway/Data/Stat.g.cs: a constant for every stat of the client's Stats table (key = row + 1,
StatCatalog), so the rules name stats by id instead of by string. Run from the repository root after a client patch
changes the Stats table (data/client.db, built from sql/ by live.ps1):

    python scripts/dev/stat_ids.py

The names: the stat's Id in PascalCase, '+' as Plus, '%' as Pct, '-' as Minus, a leading digit after an underscore
(attack_speed_+% -> AttackSpeedPlusPct). The Gateway checks the file against the running build's table at startup
(Stat.Checksum).
"""
import os
import re
import sqlite3

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "src", "GameServer.Gateway", "Data", "Stat.g.cs")


def ident(name):
    words = re.split(r"_+", name.replace("+", "_Plus_").replace("%", "_Pct_").replace("-", "_Minus_"))
    text = "".join(w[:1].upper() + w[1:] for w in words if w)
    text = re.sub(r"[^A-Za-z0-9]", "", text)
    return "_" + text if not text or text[0].isdigit() else text


def checksum(names):
    # FNV-1a over the names joined by newlines (StatCatalog.Checksum computes the same).
    h = 0xcbf29ce484222325
    for b in "\n".join(names).encode("utf-8"):
        h = ((h ^ b) * 0x100000001b3) & 0xFFFFFFFFFFFFFFFF
    return h


def main():
    db = sqlite3.connect(os.path.join(ROOT, "data", "client.db"))
    names = [r[0] or "" for r in db.execute("SELECT Id FROM Stats ORDER BY _row")]
    used = {}
    lines = []
    for row, name in enumerate(names):
        if not name:
            continue
        key = row + 1
        n = ident(name)
        if n in used:
            n = f"{n}_{key}"
        used[n] = key
        lines.append(f"    public const uint {n} = {key}; // {name}")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("// <auto-generated> scripts/dev/stat_ids.py from the client's Stats table. Do not edit. </auto-generated>\n")
        f.write("#pragma warning disable CS1591\n\n")
        f.write("/// <summary>The client's stats by key (Stats.dat row + 1), checked against the running build at startup.</summary>\n")
        f.write("public static partial class Stat\n{\n")
        f.write(f"    /// <summary>The Stats table this file was made from (StatCatalog.Checksum).</summary>\n")
        f.write(f"    public const ulong Checksum = 0x{checksum(names):016x};\n\n")
        f.write("\n".join(lines))
        f.write("\n}\n")
    print(f"{OUT}: {len(lines)} stats")


if __name__ == "__main__":
    main()
