# usage: gen_components.py   -- Agents/docs/re/components.json -> Agents/docs/re/components.md and the VT/DESER tables of
# scripts/re/frida/check-components.js (run it again after schema_md.py: DESER keeps the functions that read). Regenerate
# the JSON first with
#   bash scripts/re/ghidra/g.sh ComponentRegistry.java 'C:\...\Agents\docs\re\components.json'
import importlib.util, json, os, re, sys

sys.dont_write_bytecode = True

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(REPO, "Agents", "docs", "re", "components.json")
MD = os.path.join(REPO, "Agents", "docs", "re", "components.md")
JS = os.path.join(REPO, "scripts", "re", "frida", "check-components.js")

spec = importlib.util.spec_from_file_location("ot", os.path.join(REPO, "scripts", "re", "ot_components.py"))
ot = importlib.util.module_from_spec(spec)
spec.loader.exec_module(ot)
LIVE = {v for vts in ot.GROUND_TRUTH.values() for v in vts}

d = json.load(open(SRC))
regs = d["registrations"]
comps = [r for r in regs if r["typeId"] >= 0 or r["name"].startswith("Client")]
others = [r for r in regs if r not in comps]


def vt_cell(v):
    s = f"`{v['vt']}`" + (" ★" if v["vt"] in LIVE else "")
    if "slot17" in v:
        k = v["slot17Kind"]
        s += f" → `{v['slot17']}`" + {"ret": " (ret)", "fwd20": f" → slot 20 `{v.get('slot20')}`"}.get(k, "")
    if v.get("subclassVia"):
        s += f" (subclass of {v['subclassVia']})"
    return s


L = ["# Component registry (generated)", "",
     "Generated by `scripts/re/ghidra/ComponentRegistry.java` (→ [components.json](components.json)) and",
     "`python -I scripts/re/gen_components.py`. Do not edit by hand.", "",
     "Every caller of the pool registration `0x140e35f40` (`lea rdx,\"Name\"; lea rcx,pool; call`, static initializers",
     "in `0x14006xxxx`). For each: the pool, its users (the factory allocates from the pool; the other user is usually",
     "the atexit destructor), every vtable the users install (directly or through callees up to depth 2: the component's",
     "own vtable and those of its members), and subclass vtables (installed by functions that also install, or call one",
     "that installs, a found vtable, and that share at least three non-trivial slots with it). Slot 17 (`+0x88`) is the",
     "deserializer `0x141ec4a40` calls; \"→ slot 20\" means slot 17 is the shared forwarder that calls slot 20 (`+0xa0`).",
     "", "**Which vtable is live is not decided statically.** The client often instantiates a subclass: the player's",
     "Stats is `0x1435e7f88` (subclass, registered again as `ClientInternalStats`) while the Stats factory installs",
     "`0x1435ab340` (slot 17 `ret`); Player, Actor and AreaTransition run as `ClientPlayer`, `ClientActor` and",
     "`ClientAreaTransition`. ★ marks the vtables seen on live objects (Frida: the player and the AreaTransition exit,",
     "[../protocol/04](../protocol/04-player-entity.md), [../protocol/08](../protocol/08-area-transitions.md)).",
     "`scripts/re/frida/check-components.js` logs the live vtable and bytes of any object.", "",
     "Vtable lists include member objects' vtables (short or unrelated classes, often with a meaningless slot 17); the",
     "first vtable a factory installs is usually the component's.", "",
     f"Component type ids are indices into the name table `0x142fe6f10` ({len(d['typeTable'])} names; read by the",
     "`Error: Dependency` message, `0x14247b130`). `-1`: a `Client*` class registered under its own name.", "",
     "| Id | Name | Init | Pool | Users (factory first) | Vtables → slot 17 |", "|---|---|---|---|---|---|"]
for r in sorted(comps, key=lambda r: (r["typeId"] if r["typeId"] >= 0 else 999, r["name"])):
    users = ", ".join(f"`{u['func']}`" for u in sorted(r["users"], key=lambda u: -len(u["vtables"])))
    vts = [v for v in r["vtables"] if "slot17" in v and v.get("slot17Kind") != "noinsn"]
    cell = "<br>".join(vt_cell(v) for v in vts) or "—"
    hidden = len(r["vtables"]) - len(vts)
    if hidden:
        cell += f"<br>(+{hidden} short vtables)"
    L.append(f"| {r['typeId']} | {r['name']} | `{r['init']}` | `{r['pool']}` | {users or '—'} | {cell} |")
prim = {v["vt"] for r in comps for v in r["vtables"] if v.get("primary")}
L += ["", "Live vtables (★) that are not flagged `primary` (the read-sequence pass skips them): " +
      (", ".join(f"`{v}`" for v in sorted(LIVE - prim)) or "none") + ". `primary` = each factory's first full-size vtable,",
      "the last vtable it (or its constructor) stores at `[obj+0]`, and their subclasses."]
missing = [n for n in d["typeTable"] if n not in {r["name"] for r in regs}]
L += ["", f"Names in the type table without a registration in this client ({len(missing)}; server-side classes):",
      ", ".join(missing), "", "## Other pools registered through `0x140e35f40`", "",
      ", ".join(f"{r['name']} (`{r['pool']}`)" for r in others), ""]
open(MD, "w", encoding="utf-8", newline="\n").write("\n".join(L))

# Frida tables.
vt_names, deser = {}, {}
for r in comps:
    for v in r["vtables"]:
        vt_names.setdefault(v["vt"], [])
        if r["name"] not in vt_names[v["vt"]]:
            vt_names[v["vt"]].append(r["name"])
        if not v.get("primary"):
            continue
        if v.get("slot17Kind") == "code":
            deser.setdefault(v["slot17"], set()).add(f"{r['name']} {v['vt']} slot17")
        if v.get("slot17Kind") == "fwd20" and v.get("slot20"):
            deser.setdefault(v["slot20"], set()).add(f"{r['name']} {v['vt']} slot20")
# Keep only functions that read (Agents/docs/protocol/schema.json, from schema_md.py): slot-17 stubs shared by many classes
# (0x1400ed720, ...) are hot code elsewhere and read nothing.
SCHEMA = os.path.join(REPO, "Agents", "docs", "protocol", "schema.json")
if os.path.exists(SCHEMA):
    sums = json.load(open(SCHEMA, encoding="utf-8"))["summaries"]
    deser = {k: v for k, v in deser.items() if k in sums and sums[k]["reads"]}
gen = ["// BEGIN GENERATED (scripts/re/gen_components.py from Agents/docs/re/components.json)",
       "const VT = " + json.dumps({k: "/".join(v) for k, v in sorted(vt_names.items())}, separators=(",", ":")) + ";",
       "const DESER = " + json.dumps({k: sorted(v) for k, v in sorted(deser.items())}, separators=(",", ":")) + ";",
       "// END GENERATED"]
js = open(JS, encoding="utf-8").read()
js = re.sub(r"// BEGIN GENERATED.*?// END GENERATED", lambda m: "\n".join(gen), js, flags=re.S)
open(JS, "w", encoding="utf-8", newline="\n").write(js)
print(f"{len(comps)} component registrations, {len(others)} other pools -> {MD}; {len(deser)} deserializers -> {JS}")
