-- The first stats built from parts alone: 31 trigger stats that did nothing before are rules made only of parts the
-- tables already had (curses on hit by chance and by level, Arcane Surge and Onslaught gains, charges gained and
-- lost, Blind, Maim, Crush, Withered and Intimidate under conditions). Nothing in the code handled them, so the
-- switch turns them on and off: with the rules off they do nothing, as before. The only new code is five facts about
-- the monster a hit lands on (poisoned, chilled, shocked, blinded, cursed), read when a rule asks.
-- Also: "chance to Blind Enemies on Hit with Spells" joins the summed chance of blind_on_hit.
UPDATE fx_conditions SET takes = 'is: frozen, ignited, bleeding, poisoned, chilled, shocked, blinded, cursed, marked, killed; five_poisons (5 or more poisons on it, for a kill)',
    note = 'The trigger''s enemy is in that state as the hit found it, before the hit''s own ailments and debuffs (killed: the hit killed it).'
WHERE id = 'enemy_state';
UPDATE fx_conditions SET takes = takes || '; for skill_use also warcry, movement, travel, strike, slam, channelled, brand, aura, guard' WHERE id = 'skill_type' AND takes NOT LIKE '%warcry%';
