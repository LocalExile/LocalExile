-- Skill-specific stats: "40% increased Fireball Damage" is the general stat (increased damage) for one skill. One
-- table says which skill a character's stat is for and which stat of that skill it adds to; the skill's own stats
-- get it where they are put together, so everything that already reads the general stat from a skill (as it does a
-- support gem's or a gem's quality) reads this too. 328 stats on 889 lines (mostly helmet enchantments) that no code
-- read: damage, area of effect, duration, cooldown recovery, attack, cast and projectile speed, critical strike
-- chance, additional projectiles, arrows, chains and pierces, and curse effect, each for one skill. The skill is
-- named as the stat names it (an ActiveSkills Id, or a GrantedEffects Id in lower case with underscores).
CREATE TABLE fx_skill_stats (
    stat TEXT NOT NULL,
    ord INTEGER NOT NULL DEFAULT 0,
    skill TEXT NOT NULL,
    gives TEXT NOT NULL,
    scale REAL NOT NULL DEFAULT 1,
    enabled INTEGER NOT NULL DEFAULT 1 CHECK (enabled IN (0, 1)),
    checked INTEGER NOT NULL DEFAULT 0 CHECK (checked IN (0, 1)),
    note TEXT,
    PRIMARY KEY (stat, ord)
) STRICT;
