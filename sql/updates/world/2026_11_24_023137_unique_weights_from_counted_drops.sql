-- Unique drop weights by rarity tier, for the 522 drop-anywhere uniques whose tier is certain.
-- unique_weights is 1 / disenchant value, and that value is 1.03^(drop level - 1) x a tier coefficient (5: 1, 4: 1.25,
-- 3: 2, 2: 6, 1: 25, 0: 100; the PoE wiki's "Analysis of unique item tiers"), so it made a unique rarer the later it
-- drops: a tier 5 that starts dropping at level 70 weighed 0.13 and one from level 1 weighed 1.
-- Here a unique's tier is read back from its 3.29 disenchant value (the one tier whose coefficient gives a whole drop
-- level) and checked against the wiki's list; its weight is its tier's: 0.42, 0.315, 0.0605, 0.0109 for tiers 5 to 2.
-- Tier 5 keeps the median it had; the others follow how often each tier dropped beside it in a players' log of
-- 23,872 unique drops (per unique: tier 4 0.75, tier 3 0.144, tier 2 0.026 of a tier 5).
-- 222 go up and 300 go down. Ruthless takes the tier's median Ruthless weight.
-- Left alone: tiers 0 and 1 (too few drops to tell), a unique whose tier the wiki and
-- the 3.29 value disagree on (it changed, or became a boss, Bestiary or Mercenary drop), and every unique not in the log.
