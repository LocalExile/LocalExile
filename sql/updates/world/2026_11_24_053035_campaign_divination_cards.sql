    area_id TEXT NOT NULL,
    area_name TEXT NOT NULL,
    card_id TEXT NOT NULL,
    min_map_tier INTEGER NOT NULL CHECK (min_map_tier BETWEEN 0 AND 16),
    source TEXT NOT NULL,
    PRIMARY KEY (area_id, card_id)
) STRICT;

