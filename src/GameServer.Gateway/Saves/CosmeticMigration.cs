/// <summary>
/// Worn cosmetics saved by a 3.29.3b build. Those saves name the pick only by its record, a MtxTypes row + 1, and
/// 3.29.3c inserted and removed MtxTypes rows (from row 5081 on), so the same number now names another cosmetic. A pick
/// saved since names its MtxTypes HASH32 too (<see cref="CharacterSaves.SavedCosmetic.Hash"/>), which no version changes.
/// </summary>
public static class CosmeticMigration
{
    // 3.29.3b MtxTypes rows -> 3.29.3c rows, matched by MtxTypes.Id with an unchanged HASH32: (first row, last row, shift).
    // A row in no range was removed. Generated by scripts/re/port/mtx_remap.py from the two clients' tables:
    // 8411 rows -> 8557 rows, 8365 kept in 19 ranges, 46 removed.
    static readonly (int First, int Last, int Shift)[] From3293b =
    [
        (0, 5080, 0), (5082, 5190, 0), (5192, 5336, 0), (5348, 5355, 0), (5362, 5367, 0), (5374, 5394, 0),
        (5396, 5485, 0), (5487, 5497, 0), (5499, 5499, 0), (5506, 5509, 0), (5510, 5520, 2), (5522, 5596, 2),
        (5602, 5602, 2), (5608, 5609, 2), (5611, 5613, 2), (5614, 5617, 7), (5618, 6145, 69), (6146, 7704, 76),
        (7705, 8410, 120),
    ];

    /// <summary>The 3.29.3c record of a record a 3.29.3b build saved, or null when 3.29.3c removed that cosmetic.</summary>
    public static uint? Record3293c(uint record3293b)
    {
        long row = (long)record3293b - 1;
        foreach (var (first, last, shift) in From3293b)
            if (row >= first && row <= last) return (uint)(row + shift + 1);
        return null;
    }
}
